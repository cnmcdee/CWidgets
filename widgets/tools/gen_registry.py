#!/usr/bin/env python3
"""Generate common/registry.h: the single source of truth for the palette
and layout apps — widget names (canonical sorted order), section index per
widget, section names, default placement sizes, and a type-erased factory
that can instantiate ANY of the 194 XFrame widget classes through one
interface (all 194 share the same constructor + event-method signatures).

Also regenerates the section table in README.md (between the
<!-- SECTIONS:BEGIN --> / <!-- SECTIONS:END --> markers).

Usage: python3 tools/gen_registry.py   (run from the repo root)
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from sections import SECTIONS, ASSIGNMENT, section_of, validate  # noqa: E402


def default_size(name):
    """Sensible default placement size (w, h) for a widget type."""
    n = name.lower()
    if "spreadsheet" in n or "graph" in n:
        return (320, 200)
    if "dialog" in n or "window" in n or "assistant" in n or n.endswith("form"):
        return (300, 220)
    if any(k in n for k in ("treeview", "listview", "grid", "columnview",
                            "shelltree", "shelllist", "drawgrid", "stringgrid",
                            "textview", "memo", "notebook", "pagecontrol",
                            "tabcontrol", "stack")):
        return (260, 180)
    if any(k in n for k in ("button", "check", "radio", "toggle", "switch",
                            "updown", "spin")):
        return (150, 36)
    if any(k in n for k in ("label", "entry", "edit", "combo", "scale",
                            "slider", "scrollbar", "separator", "statusbar",
                            "search", "progressbar", "levelbar")):
        return (180, 30)
    return (200, 90)


HEADER = """// GENERATED by tools/gen_registry.py — do not edit by hand.
// Canonical widget list (sorted), section assignment, default sizes,
// and a type-erased factory over all 194 XFrame widget classes.
#pragma once

#include <memory>
#include <string>
#include <vector>

#include "core/xframe_core.h"
{includes}

namespace cw {{

inline const int kWidgetCount = {count};
inline const int kSectionCount = {nsec};

inline const char* kSectionNames[kSectionCount] = {{
{sections}
}};

inline const char* kWidgetNames[kWidgetCount] = {{
{names}
}};

// Section index (into kSectionNames) for each widget, same order as names.
inline const int kWidgetSection[kWidgetCount] = {{
{widget_sections}
}};

// Default placement size (w, h) per widget type.
inline const int kWidgetDefaultW[kWidgetCount] = {{ {defw} }};
inline const int kWidgetDefaultH[kWidgetCount] = {{ {defh} }};

inline int index_of(const std::string& name) {{
    for (int i = 0; i < kWidgetCount; ++i)
        if (name == kWidgetNames[i]) return i;
    return -1;
}}

// One interface over every widget class: all 194 share the same
// constructor signature and the same event-method signatures.
struct IWidget {{
    virtual ~IWidget() {{}}
    virtual void draw() = 0;
    virtual void set_bounds(int x, int y, int w, int h) = 0;
    virtual bool contains(int x, int y) = 0;
    virtual bool on_button_press(int x, int y, unsigned int b) = 0;
    virtual bool on_button_release(int x, int y, unsigned int b) = 0;
    virtual bool on_motion(int x, int y) = 0;
    virtual bool on_key(KeySym k, const char* s) = 0;
    virtual int width() = 0;
    virtual int height() = 0;
}};

template <typename T>
struct Holder : IWidget {{
    T w;
    Holder(Display* d, int s, Window win, GC gc, SStyle_Manager* st,
           int x, int y, int ww, int hh)
        : w(d, s, win, gc, st, x, y, ww, hh) {{}}
    void draw() override {{ w.draw(); }}
    void set_bounds(int x, int y, int ww, int hh) override {{ w.set_bounds(x, y, ww, hh); }}
    bool contains(int x, int y) override {{ return w.contains(x, y); }}
    bool on_button_press(int x, int y, unsigned int b) override {{ return w.on_button_press(x, y, b); }}
    bool on_button_release(int x, int y, unsigned int b) override {{ return w.on_button_release(x, y, b); }}
    bool on_motion(int x, int y) override {{ return w.on_motion(x, y); }}
    bool on_key(KeySym k, const char* s) override {{ return w.on_key(k, s); }}
    int width() override {{ return w.width(); }}
    int height() override {{ return w.height(); }}
}};

inline std::unique_ptr<IWidget> create_widget(int type, Display* d, int s,
        Window win, GC gc, SStyle_Manager* st, int x, int y, int w, int h) {{
    switch (type) {{
{cases}        default: return nullptr;
    }}
}}

}} // namespace cw
"""


def main():
    comps = sorted(os.listdir(os.path.join(ROOT, "components")))
    errs = validate(comps)
    if errs:
        for e in errs:
            print("SECTION ERROR: " + e, file=sys.stderr)
        return 1
    includes = "\n".join(
        f'#include "components/{n}/{n}.h"' for n in comps)
    sections = ",\n".join(f'    "{s}"' for s in SECTIONS)
    names = ",\n".join(f'    "{n}"' for n in comps)
    wsec = ",\n".join(
        "    " + ", ".join(
            str(SECTIONS.index(section_of(n))) for n in comps[i:i + 12])
        for i in range(0, len(comps), 12))
    sizes = [default_size(n) for n in comps]
    defw = ", ".join(str(w) for w, _ in sizes)
    defh = ", ".join(str(h) for _, h in sizes)
    cases = "\n".join(
        f"        case {i}: return std::make_unique<Holder<{n}>>(d, s, win, gc, st, x, y, w, h);"
        for i, n in enumerate(comps))
    text = HEADER.format(
        includes=includes, count=len(comps), nsec=len(SECTIONS),
        sections=sections, names=names, widget_sections=wsec,
        defw=defw, defh=defh, cases=cases)
    out = os.path.join(ROOT, "common", "registry.h")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write(text)
    print(f"wrote {out} ({len(comps)} widgets, {len(SECTIONS)} sections)")

    # README section table.
    readme = os.path.join(ROOT, "README.md")
    lines = ["## Palette sections (194 widgets)\n"]
    for sec in SECTIONS:
        names_sec = ASSIGNMENT[sec]
        lines.append(f"\n### {sec} ({len(names_sec)})\n\n")
        lines.append(", ".join(f"`{n}`" for n in names_sec) + "\n")
    table = "".join(lines)
    if os.path.exists(readme):
        with open(readme) as f:
            content = f.read()
    else:
        # No widgets README yet (fresh combined tree): start a new one.
        content = "# CWidgets \u2014 XFrame widgets\n"
    begin = "<!-- SECTIONS:BEGIN -->"
    end = "<!-- SECTIONS:END -->"
    if begin in content and end in content:
        pre = content.split(begin)[0]
        post = content.split(end, 1)[1]
        content = pre + begin + "\n\n" + table + "\n" + end + post
    else:
        content = content.rstrip() + "\n\n" + begin + "\n\n" + table + "\n" + end + "\n"
    with open(readme, "w") as f:
        f.write(content)
    print("README section table updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
