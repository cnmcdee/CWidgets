CTOR = "(Display* display, int screen, Window window, GC gc, SStyle_Manager* styles, int x, int y, int width, int height)"

def render(fname, title, intro, widgets):
    lines = []
    lines.append("# " + title)
    lines.append("")
    lines.append(intro)
    lines.append("")
    lines.append("> Every widget here shares the common XFrame widget API \u2014 same constructor, set_bounds/draw/event handlers, visible/enabled state. The shared contract is documented in docs/index.md (written by the coordinator). Each subsection below lists only what is specific to that widget.")
    lines.append("")
    for (name, desc, api, notes) in widgets:
        lines.append("## " + name)
        lines.append("")
        lines.append(desc)
        lines.append("")
        lines.append("**Constructor:** `" + name + CTOR + "`")
        lines.append("")
        lines.append("**API** (widget-specific methods/properties/signals ONLY \u2014 skip the common ones):")
        for a in api:
            lines.append(a)
        lines.append("")
        lines.append("**Example:**")
        lines.append("```cpp")
        with open(os.path.join(EXDIR, name + ".cpp")) as f:
            lines.append(f.read().rstrip("\n"))
        lines.append("```")
        lines.append("")
        lines.append("**Notes:** " + (notes if notes else "None."))
        lines.append("")
    return "\n".join(lines) + "\n"

