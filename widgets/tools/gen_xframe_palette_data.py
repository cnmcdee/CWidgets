#!/usr/bin/env python3
"""Generate designer/src/xframe_palette.h: the XFrame widgets in their
section groups, for the combined IDE palette.

Sources of truth (read, never duplicated by hand):
  - widgets/tools/sections.py: SECTIONS order + ASSIGNMENT (name -> section)
  - widgets/common/registry.h: kWidgetNames order -> the registry index
    each widget carries in the palette -> layout selection file.

Usage: python3 widgets/tools/gen_xframe_palette_data.py [--check]
  --check: regenerate to a temp file and diff against the committed
  header instead of writing (used by tests/test_combined_palette.py).
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import sections as secmod
from widget_count import registry_names as wc_registry_names


def registry_names():
    # Single shared derivation (tools/widget_count.py): the registry is
    # the canonical list; the count follows it, never a hard-coded number.
    return wc_registry_names()


def build_header():
    """Return (header text, entry count, section count), all derived."""
    names = registry_names()
    n = len(names)
    index = {nm: i for i, nm in enumerate(names)}
    # Entries are driven by the registry, in sections.py order within
    # each section (the order the palette has always shown). A widget
    # assigned to a section but not yet in the registry (landed on disk,
    # registry not regenerated) is skipped; a section with no registry
    # widget yet (e.g. Stock Market right now) is omitted entirely.
    entries = []
    seen = set()
    for section in secmod.SECTIONS:
        for name in secmod.ASSIGNMENT.get(section, []):
            if name not in index:
                continue
            assert name not in seen, f"duplicate {name} in sections.py"
            seen.add(name)
            entries.append((name, section, index[name]))
    assert seen == set(names), "sections.py and registry.h disagree on the widget set"
    used_sections = [s for s in secmod.SECTIONS
                     if any(e[1] == s for e in entries)]
    counts = {s: sum(1 for e in entries if e[1] == s) for s in used_sections}

    lines = []
    lines.append("// GENERATED by widgets/tools/gen_xframe_palette_data.py — do not edit by hand.")
    lines.append(f"// The {n} XFrame widgets in their {len(used_sections)} section groups, in section order,")
    lines.append("// for the combined IDE palette (designer/src/main.cpp). `index` is the")
    lines.append("// widget's index in widgets/common/registry.h (kWidgetNames) — the same")
    lines.append("// index the palette -> layout selection file carries.")
    lines.append("// Section counts: " + ", ".join(
        f"{s} {counts[s]}" for s in used_sections) + ".")
    lines.append("#pragma once")
    lines.append("")
    lines.append("struct XFramePaletteEntry {")
    lines.append("    const char* name;     // e.g. \"GtkButton\"")
    lines.append("    const char* section;  // e.g. \"Buttons\"")
    lines.append(f"    int index;            // registry index, 0..{n - 1}")
    lines.append("};")
    lines.append("")
    lines.append("inline const char* kXFrameSections[] = {")
    for s in used_sections:
        lines.append(f'    "{s}",')
    lines.append("};")
    lines.append(f"inline const int kXFrameSectionCount = {len(used_sections)};")
    lines.append("")
    lines.append("inline const XFramePaletteEntry kXFramePalette[] = {")
    for name, section, idx in entries:
        lines.append(f'    {{"{name}", "{section}", {idx}}},')
    lines.append("};")
    lines.append(f"inline const int kXFramePaletteCount = {n};")
    lines.append("")
    return "\n".join(lines), n, len(used_sections)


def main():
    check = "--check" in sys.argv
    text, n_entries, n_sections = build_header()
    out = os.path.join(ROOT, "designer", "src", "xframe_palette.h")
    if check:
        import tempfile
        with tempfile.NamedTemporaryFile("w", suffix=".h", delete=False) as f:
            f.write(text)
            tmp = f.name
        import subprocess
        r = subprocess.run(["diff", "-u", out, tmp])
        os.unlink(tmp)
        print("xframe_palette.h is current" if r.returncode == 0
              else "xframe_palette.h is STALE — re-run gen_xframe_palette_data.py")
        return r.returncode
    with open(out, "w") as f:
        f.write(text)
    print(f"wrote {out} ({n_entries} entries, {n_sections} sections)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
